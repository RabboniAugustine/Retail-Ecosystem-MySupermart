-- ============================================================================
-- 001_base_schema.sql
-- Creates every table the app uses, or adds the missing columns if the
-- tables already exist. Safe to run more than once.
-- Run this FIRST in the Supabase SQL Editor.
-- ============================================================================

-- ── Products ────────────────────────────────────────────────────────────────
create table if not exists public.ms_products (
  id          bigint generated by default as identity primary key,
  name        text not null,
  sku         text unique,
  category    text default 'Other',
  barcode     text,
  price       numeric(12,2) not null default 0,
  cost        numeric(12,2) not null default 0,
  created_at  timestamptz not null default now()
);
alter table public.ms_products add column if not exists active boolean not null default true;
alter table public.ms_products add column if not exists created_at timestamptz not null default now();
create index if not exists ms_products_barcode_idx on public.ms_products (barcode);

-- ── Inventory (one row per product) ─────────────────────────────────────────
create table if not exists public.ms_inventory (
  id             bigint generated by default as identity primary key,
  product_id     bigint not null unique references public.ms_products(id) on delete cascade,
  stock          integer not null default 0,
  reorder_level  integer not null default 0,
  expiry_date    date,
  supplier       text,
  updated_at     timestamptz not null default now()
);

-- ── Customers ───────────────────────────────────────────────────────────────
create table if not exists public.ms_customers (
  id             bigint generated by default as identity primary key,
  name           text not null,
  customer_code  text unique,
  joined_date    date not null default current_date,
  total_spent    numeric(14,2) not null default 0,
  visit_count    integer not null default 0,
  points         integer not null default 0,
  tier           text not null default 'Bronze',
  last_visit     date
);
alter table public.ms_customers add column if not exists phone text;
alter table public.ms_customers add column if not exists email text;

-- ── Suppliers ───────────────────────────────────────────────────────────────
create table if not exists public.ms_suppliers (
  id            bigint generated by default as identity primary key,
  name          text not null,
  contact_name  text,
  category      text,
  rating        numeric(3,1) not null default 4.5,
  payable       numeric(14,2) not null default 0
);
alter table public.ms_suppliers add column if not exists phone text;

-- ── Sales ───────────────────────────────────────────────────────────────────
create table if not exists public.ms_transactions (
  id              bigint generated by default as identity primary key,
  txn_code        text unique,
  customer_id     bigint references public.ms_customers(id) on delete set null,
  subtotal        numeric(14,2) not null default 0,
  discount_pct    numeric(5,2) not null default 0,
  tax             numeric(14,2) not null default 0,
  total           numeric(14,2) not null default 0,
  payment_method  text not null default 'Cash',
  status          text not null default 'Completed',
  created_at      timestamptz not null default now()
);
alter table public.ms_transactions add column if not exists cashier_id uuid references auth.users(id) on delete set null;
alter table public.ms_transactions add column if not exists cashier_name text;
alter table public.ms_transactions add column if not exists discount_amount numeric(14,2) not null default 0;
alter table public.ms_transactions add column if not exists amount_tendered numeric(14,2);
alter table public.ms_transactions add column if not exists change_due numeric(14,2);
alter table public.ms_transactions add column if not exists points_earned integer not null default 0;
alter table public.ms_transactions add column if not exists refunded_at timestamptz;
alter table public.ms_transactions add column if not exists refunded_by uuid references auth.users(id) on delete set null;
alter table public.ms_transactions add column if not exists refund_reason text;
create index if not exists ms_transactions_created_idx on public.ms_transactions (created_at desc);
create index if not exists ms_transactions_cashier_idx on public.ms_transactions (cashier_id, created_at desc);

create table if not exists public.ms_transaction_items (
  id              bigint generated by default as identity primary key,
  transaction_id  bigint not null references public.ms_transactions(id) on delete cascade,
  product_id      bigint references public.ms_products(id) on delete set null,
  quantity        integer not null,
  unit_price      numeric(12,2) not null,
  line_total      numeric(14,2) not null
);
alter table public.ms_transaction_items add column if not exists product_name text;
alter table public.ms_transaction_items add column if not exists unit_cost numeric(12,2);
create index if not exists ms_transaction_items_txn_idx on public.ms_transaction_items (transaction_id);

-- ── Expenses ────────────────────────────────────────────────────────────────
create table if not exists public.ms_expenses (
  id           bigint generated by default as identity primary key,
  description  text not null,
  category     text not null default 'Other',
  amount       numeric(14,2) not null,
  date         date not null default current_date
);
alter table public.ms_expenses add column if not exists created_by uuid references auth.users(id) on delete set null;

-- ── Product removal log ─────────────────────────────────────────────────────
create table if not exists public.ms_product_removals (
  id            bigint generated by default as identity primary key,
  product_id    bigint,
  product_name  text,
  sku           text,
  quantity      integer not null default 0,
  unit_cost     numeric(12,2) not null default 0,
  loss_value    numeric(14,2) not null default 0,
  reason        text not null,
  note          text,
  removed_at    timestamptz not null default now()
);
alter table public.ms_product_removals add column if not exists removed_by uuid references auth.users(id) on delete set null;
alter table public.ms_product_removals add column if not exists removed_by_name text;

-- ── Stock movement log (NEW): every stock change, who made it and why ───────
create table if not exists public.ms_stock_movements (
  id               bigint generated by default as identity primary key,
  product_id       bigint references public.ms_products(id) on delete set null,
  product_name     text,
  old_stock        integer not null,
  new_stock        integer not null,
  change           integer not null,
  reason           text not null,
  created_by       uuid references auth.users(id) on delete set null,
  created_by_name  text,
  created_at       timestamptz not null default now()
);
create index if not exists ms_stock_movements_created_idx on public.ms_stock_movements (created_at desc);

-- Products that exist without an inventory row get one (stock 0).
insert into public.ms_inventory (product_id, stock, reorder_level)
select p.id, 0, 0 from public.ms_products p
where not exists (select 1 from public.ms_inventory i where i.product_id = p.id);
