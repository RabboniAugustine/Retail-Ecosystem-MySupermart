-- ============================================================================
-- 007_repair_legacy_tables.sql
-- Fixes databases that were first set up with the ORIGINAL version of the app
-- (schema.sql / product_removal.sql). Those tables already existed, so 001 did
-- not recreate them and some columns the app now uses were missing, e.g.
--   column "product_id" of relation "ms_product_removals" does not exist
--
-- What it does, without touching any existing data:
--   1. adds every column the app expects, if it is missing;
--   2. relaxes old required columns the app no longer fills in, so inserts work.
-- Safe to run more than once. Run AFTER 006.
-- ============================================================================

-- ── 1. Columns the app expects ─────────────────────────────────────────────
-- Product removal log
alter table public.ms_product_removals add column if not exists id bigint generated by default as identity;
alter table public.ms_product_removals add column if not exists product_id bigint;
alter table public.ms_product_removals add column if not exists product_name text;
alter table public.ms_product_removals add column if not exists sku text;
alter table public.ms_product_removals add column if not exists quantity integer not null default 0;
alter table public.ms_product_removals add column if not exists unit_cost numeric(12,2) not null default 0;
alter table public.ms_product_removals add column if not exists loss_value numeric(14,2) not null default 0;
alter table public.ms_product_removals add column if not exists reason text;
alter table public.ms_product_removals add column if not exists note text;
alter table public.ms_product_removals add column if not exists removed_at timestamptz not null default now();
alter table public.ms_product_removals add column if not exists removed_by uuid references auth.users(id) on delete set null;
alter table public.ms_product_removals add column if not exists removed_by_name text;

-- Products and stock
alter table public.ms_products add column if not exists sku text;
alter table public.ms_products add column if not exists category text default 'Other';
alter table public.ms_products add column if not exists barcode text;
alter table public.ms_products add column if not exists cost numeric(12,2) not null default 0;
alter table public.ms_products add column if not exists active boolean not null default true;
alter table public.ms_products add column if not exists created_at timestamptz not null default now();
alter table public.ms_inventory add column if not exists reorder_level integer not null default 0;
alter table public.ms_inventory add column if not exists expiry_date date;
alter table public.ms_inventory add column if not exists supplier text;
alter table public.ms_inventory add column if not exists updated_at timestamptz not null default now();

-- Customers and suppliers
alter table public.ms_customers add column if not exists customer_code text;
alter table public.ms_customers add column if not exists joined_date date not null default current_date;
alter table public.ms_customers add column if not exists total_spent numeric(14,2) not null default 0;
alter table public.ms_customers add column if not exists visit_count integer not null default 0;
alter table public.ms_customers add column if not exists points integer not null default 0;
alter table public.ms_customers add column if not exists tier text not null default 'Bronze';
alter table public.ms_customers add column if not exists last_visit date;
alter table public.ms_customers add column if not exists phone text;
alter table public.ms_customers add column if not exists email text;
alter table public.ms_suppliers add column if not exists contact_name text;
alter table public.ms_suppliers add column if not exists category text;
alter table public.ms_suppliers add column if not exists rating numeric(3,1) not null default 4.5;
alter table public.ms_suppliers add column if not exists payable numeric(14,2) not null default 0;
alter table public.ms_suppliers add column if not exists phone text;

-- Sales
alter table public.ms_transactions add column if not exists discount_pct numeric(5,2) not null default 0;
alter table public.ms_transactions add column if not exists status text not null default 'Completed';
alter table public.ms_transaction_items add column if not exists product_name text;
alter table public.ms_transaction_items add column if not exists unit_cost numeric(12,2);

-- Expenses
alter table public.ms_expenses add column if not exists category text not null default 'Other';
alter table public.ms_expenses add column if not exists date date not null default current_date;

-- ── 2. Relax old required columns the app does not fill in ─────────────────
-- (Only columns that are NOT in the app's own design, are required, and have no default.)
do $$
declare
  r record;
  expected jsonb := jsonb_build_object(
    'ms_product_removals', jsonb_build_array('id','product_id','product_name','sku','quantity','unit_cost','loss_value','reason','note','removed_at','removed_by','removed_by_name'),
    'ms_products',         jsonb_build_array('id','name','sku','category','barcode','price','cost','active','created_at'),
    'ms_inventory',        jsonb_build_array('id','product_id','stock','reorder_level','expiry_date','supplier','updated_at'),
    'ms_customers',        jsonb_build_array('id','name','customer_code','joined_date','total_spent','visit_count','points','tier','last_visit','phone','email'),
    'ms_suppliers',        jsonb_build_array('id','name','contact_name','category','rating','payable','phone'),
    'ms_transactions',     jsonb_build_array('id','txn_code','customer_id','subtotal','discount_pct','tax','total','payment_method','status','created_at',
                                             'cashier_id','cashier_name','discount_amount','amount_tendered','change_due','points_earned','refunded_at','refunded_by','refund_reason'),
    'ms_transaction_items',jsonb_build_array('id','transaction_id','product_id','quantity','unit_price','line_total','product_name','unit_cost'),
    'ms_expenses',         jsonb_build_array('id','description','category','amount','date','created_by','paid_from','created_by_name','created_at')
  );
begin
  for r in
    select c.table_name, c.column_name
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.table_name in (select jsonb_object_keys(expected))
      and c.is_nullable = 'NO'
      and c.column_default is null
      and c.is_identity = 'NO'
      and not (expected -> c.table_name) ? c.column_name
  loop
    execute format('alter table public.%I alter column %I drop not null', r.table_name, r.column_name);
    raise notice 'Relaxed old required column %.%', r.table_name, r.column_name;
  end loop;
end $$;

-- Let the API see the new columns straight away.
notify pgrst, 'reload schema';
