-- ── Staff profiles ──────────────────────────────────────────────────────────
-- role: owner    = full access
--       sales    = POS, stock and customers
--       pending  = signed up, waiting for the owner to approve
--       disabled = access removed
create table if not exists public.ms_profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text,
  email       text,
  role        text not null default 'pending'
              check (role in ('owner', 'sales', 'pending', 'disabled')),
  created_at  timestamptz not null default now()
);

-- New sign-ups get a profile automatically. The very first account becomes
-- the owner; everyone after that waits for the owner's approval.
create or replace function public.ms_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.ms_profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'full_name', ''), split_part(new.email, '@', 1)),
    new.email,
    case when exists (select 1 from public.ms_profiles where role = 'owner') then 'pending' else 'owner' end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists ms_on_auth_user_created on auth.users;
create trigger ms_on_auth_user_created
  after insert on auth.users
  for each row execute function public.ms_handle_new_user();

-- Accounts that existed before this migration get a profile too.
insert into public.ms_profiles (id, full_name, email, role)
select u.id, coalesce(nullif(u.raw_user_meta_data->>'full_name', ''), split_part(u.email, '@', 1)), u.email, 'pending'
from auth.users u
on conflict (id) do nothing;

-- If there is still no owner, the oldest account becomes the owner.
update public.ms_profiles set role = 'owner'
where id = (select id from public.ms_profiles order by created_at limit 1)
  and not exists (select 1 from public.ms_profiles where role = 'owner');

-- ── Shop settings (single row) ──────────────────────────────────────────────
create table if not exists public.ms_settings (
  id                int primary key default 1 check (id = 1),
  shop_name         text not null default 'My Supermart',
  address           text,
  phone             text,
  vat_rate          numeric(5,2) not null default 12.5,
  max_discount_pct  numeric(5,2) not null default 10,
  block_oversell    boolean not null default true,
  display_message   text not null default 'Welcome! Thank you for shopping with us.',
  receipt_footer    text not null default 'Thank you for shopping with us!',
  updated_at        timestamptz not null default now()
);
insert into public.ms_settings (id) values (1) on conflict (id) do nothing;

-- ── Role helpers used by the access rules ───────────────────────────────────
create or replace function public.ms_my_role()
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select role from public.ms_profiles where id = auth.uid()), 'none');
$$;

create or replace function public.ms_is_owner()
returns boolean language sql stable security definer set search_path = public as $$
  select public.ms_my_role() = 'owner';
$$;

create or replace function public.ms_is_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select public.ms_my_role() in ('owner', 'sales');
$$;

-- Owner changes a staff member's role (approve, disable, promote).
create or replace function public.ms_set_staff_role(p_user_id uuid, p_role text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can change staff roles'; end if;
  if p_user_id = auth.uid() then raise exception 'You cannot change your own role'; end if;
  if p_role not in ('owner', 'sales', 'pending', 'disabled') then raise exception 'Unknown role %', p_role; end if;
  update public.ms_profiles set role = p_role where id = p_user_id;
end;
$$;

-- Owner renames a staff member (or anyone renames themselves).
create or replace function public.ms_set_staff_name(p_user_id uuid, p_name text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_user_id <> auth.uid() and not public.ms_is_owner() then raise exception 'Not allowed'; end if;
  update public.ms_profiles set full_name = nullif(trim(p_name), '') where id = p_user_id;
end;
$$;

-- ── Turn on Row Level Security and remove every old policy ──────────────────
do $$
declare
  t text;
  pol record;
begin
  foreach t in array array[
    'ms_products', 'ms_inventory', 'ms_customers', 'ms_suppliers', 'ms_transactions',
    'ms_transaction_items', 'ms_expenses', 'ms_product_removals', 'ms_stock_movements',
    'ms_profiles', 'ms_settings'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    for pol in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
      execute format('drop policy %I on public.%I', pol.policyname, t);
    end loop;
  end loop;
end $$;

-- Logged-out visitors get nothing.
revoke all on
  public.ms_products, public.ms_inventory, public.ms_customers, public.ms_suppliers,
  public.ms_transactions, public.ms_transaction_items, public.ms_expenses,
  public.ms_product_removals, public.ms_stock_movements, public.ms_profiles, public.ms_settings
from anon;

-- ── Access rules ────────────────────────────────────────────────────────────
-- Profiles: you see your own; the owner sees everyone. Changes go through functions.
create policy profiles_read on public.ms_profiles for select to authenticated
  using (id = auth.uid() or public.ms_is_owner());

-- Settings: any signed-in user can read; only the owner can change.
create policy settings_read on public.ms_settings for select to authenticated using (true);
create policy settings_owner_update on public.ms_settings for update to authenticated
  using (public.ms_is_owner()) with check (public.ms_is_owner());

-- Products: staff read, add and edit; only the owner deletes (removal goes through ms_remove_product).
create policy products_read on public.ms_products for select to authenticated using (public.ms_is_staff());
create policy products_insert on public.ms_products for insert to authenticated with check (public.ms_is_staff());
create policy products_update on public.ms_products for update to authenticated
  using (public.ms_is_staff()) with check (public.ms_is_staff());
create policy products_delete on public.ms_products for delete to authenticated using (public.ms_is_owner());

-- Inventory: staff read and edit details. Stock numbers only change through
-- ms_adjust_stock / ms_checkout so every change is logged.
create policy inventory_read on public.ms_inventory for select to authenticated using (public.ms_is_staff());
create policy inventory_insert on public.ms_inventory for insert to authenticated with check (public.ms_is_staff());
create policy inventory_update on public.ms_inventory for update to authenticated
  using (public.ms_is_staff()) with check (public.ms_is_staff());
revoke update on public.ms_inventory from authenticated;
grant update (reorder_level, expiry_date, supplier, updated_at) on public.ms_inventory to authenticated;

-- Customers: staff read, add and edit; only the owner deletes.
create policy customers_read on public.ms_customers for select to authenticated using (public.ms_is_staff());
create policy customers_insert on public.ms_customers for insert to authenticated with check (public.ms_is_staff());
create policy customers_update on public.ms_customers for update to authenticated
  using (public.ms_is_staff()) with check (public.ms_is_staff());
create policy customers_delete on public.ms_customers for delete to authenticated using (public.ms_is_owner());
-- Loyalty totals are only changed by checkout/refund.
revoke update on public.ms_customers from authenticated;
grant update (name, customer_code, phone, email) on public.ms_customers to authenticated;

-- Suppliers: staff can read the list; only the owner manages it.
create policy suppliers_read on public.ms_suppliers for select to authenticated using (public.ms_is_staff());
create policy suppliers_owner_write on public.ms_suppliers for all to authenticated
  using (public.ms_is_owner()) with check (public.ms_is_owner());

-- Sales: the owner sees all sales; a salesperson sees only their own.
-- Sales are created and refunded only through ms_checkout / ms_refund.
create policy transactions_read on public.ms_transactions for select to authenticated
  using (public.ms_is_owner() or (public.ms_is_staff() and cashier_id = auth.uid()));
create policy transaction_items_read on public.ms_transaction_items for select to authenticated
  using (exists (
    select 1 from public.ms_transactions t
    where t.id = transaction_id
      and (public.ms_is_owner() or (public.ms_is_staff() and t.cashier_id = auth.uid()))
  ));

-- Owner only.
create policy expenses_owner on public.ms_expenses for all to authenticated
  using (public.ms_is_owner()) with check (public.ms_is_owner());
create policy removals_owner_read on public.ms_product_removals for select to authenticated
  using (public.ms_is_owner());
create policy movements_owner_read on public.ms_stock_movements for select to authenticated
  using (public.ms_is_owner());

revoke execute on function public.ms_set_staff_role(uuid, text) from public, anon;
revoke execute on function public.ms_set_staff_name(uuid, text) from public, anon;
grant execute on function public.ms_set_staff_role(uuid, text) to authenticated;
grant execute on function public.ms_set_staff_name(uuid, text) to authenticated;


-- ============================================================================
-- 003_pos_functions.sql
-- Database functions the app calls: checkout, refunds, stock changes,
-- adding and removing products. Each runs as one transaction: if anything
-- fails, nothing is saved. Safe to run more than once. Run AFTER 002.
-- ============================================================================

-- Remove older versions of these functions (whatever their arguments were).
do $$
declare f record;
begin
  for f in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in ('ms_checkout', 'ms_remove_product', 'ms_adjust_stock', 'ms_refund', 'ms_create_product', 'ms_tier')
  loop
    execute format('drop function %s', f.sig);
  end loop;
end $$;

-- Loyalty tier from lifetime spend (₵).
create function public.ms_tier(p_spent numeric)
returns text language sql immutable as $$
  select case
    when p_spent >= 10000 then 'Platinum'
    when p_spent >= 5000  then 'Gold'
    when p_spent >= 1500  then 'Silver'
    else 'Bronze' end;
$$;

-- ── Checkout ────────────────────────────────────────────────────────────────
-- Prices, VAT and totals are worked out here from the database, never trusted
-- from the browser. Salespeople cannot give more discount than the owner's limit.
-- p_items: [{"product_id": 1, "quantity": 2}, ...]
create function public.ms_checkout(
  p_items           jsonb,
  p_customer_id     bigint  default null,
  p_discount_pct    numeric default 0,
  p_payment_method  text    default 'Cash',
  p_amount_tendered numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role      text := public.ms_my_role();
  v_settings  public.ms_settings;
  v_name      text;
  v_txn_id    bigint;
  v_code      text;
  v_line      record;
  v_prod      record;
  v_subtotal  numeric := 0;
  v_discount  numeric;
  v_tax       numeric;
  v_total     numeric;
  v_change    numeric;
  v_points    integer := 0;
  v_cust      public.ms_customers;
  v_new_spent numeric;
  v_created   timestamptz;
begin
  if v_role not in ('owner', 'sales') then
    raise exception 'You are not allowed to make sales';
  end if;

  select * into v_settings from public.ms_settings where id = 1;
  select full_name into v_name from public.ms_profiles where id = auth.uid();

  p_discount_pct := coalesce(p_discount_pct, 0);
  if p_discount_pct < 0 or p_discount_pct > 100 then
    raise exception 'Discount must be between 0 and 100%%';
  end if;
  if v_role = 'sales' and p_discount_pct > v_settings.max_discount_pct then
    raise exception 'Discount is above your limit of %', v_settings.max_discount_pct || '%';
  end if;
  if p_payment_method not in ('Cash', 'Card', 'Mobile Money') then
    raise exception 'Unknown payment method %', p_payment_method;
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'The cart is empty';
  end if;

  insert into public.ms_transactions (txn_code, customer_id, payment_method, status, cashier_id, cashier_name, discount_pct)
  values ('TMP-' || gen_random_uuid(), p_customer_id, p_payment_method, 'Completed', auth.uid(), v_name, p_discount_pct)
  returning id, created_at into v_txn_id, v_created;

  v_code := 'TXN-' || to_char(v_created at time zone 'UTC', 'YYMMDD') || '-' || lpad(v_txn_id::text, 5, '0');

  -- Same product sent twice is merged into one line.
  for v_line in
    select (e->>'product_id')::bigint as product_id, sum((e->>'quantity')::int) as qty
    from jsonb_array_elements(p_items) e
    group by 1
  loop
    if v_line.qty is null or v_line.qty <= 0 then
      raise exception 'Quantities must be at least 1';
    end if;

    select p.id, p.name, p.price, p.cost, i.stock into v_prod
    from public.ms_products p
    join public.ms_inventory i on i.product_id = p.id
    where p.id = v_line.product_id and p.active
    for update of i;

    if not found then
      raise exception 'A product in the cart is no longer available';
    end if;
    if v_settings.block_oversell and v_prod.stock < v_line.qty then
      raise exception 'Only % of "%" left in stock', v_prod.stock, v_prod.name;
    end if;

    insert into public.ms_transaction_items (transaction_id, product_id, product_name, quantity, unit_price, unit_cost, line_total)
    values (v_txn_id, v_prod.id, v_prod.name, v_line.qty, v_prod.price, v_prod.cost, round(v_prod.price * v_line.qty, 2));

    update public.ms_inventory
    set stock = greatest(0, stock - v_line.qty), updated_at = now()
    where product_id = v_prod.id;

    v_subtotal := v_subtotal + round(v_prod.price * v_line.qty, 2);
  end loop;

  v_discount := round(v_subtotal * p_discount_pct / 100, 2);
  v_tax      := round((v_subtotal - v_discount) * v_settings.vat_rate / 100, 2);
  v_total    := v_subtotal - v_discount + v_tax;

  if p_payment_method = 'Cash' and p_amount_tendered is not null then
    if p_amount_tendered < v_total then
      raise exception 'Cash received (₵%) is less than the total (₵%)', p_amount_tendered, v_total;
    end if;
    v_change := p_amount_tendered - v_total;
  end if;

  if p_customer_id is not null then
    select * into v_cust from public.ms_customers where id = p_customer_id for update;
    if not found then raise exception 'Customer not found'; end if;
    v_points    := floor(v_total)::int;   -- 1 point per ₵1
    v_new_spent := v_cust.total_spent + v_total;
    update public.ms_customers set
      total_spent = v_new_spent,
      visit_count = visit_count + 1,
      points      = points + v_points,
      tier        = public.ms_tier(v_new_spent),
      last_visit  = current_date
    where id = p_customer_id;
  end if;

  update public.ms_transactions set
    txn_code        = v_code,
    subtotal        = v_subtotal,
    discount_amount = v_discount,
    tax             = v_tax,
    total           = v_total,
    amount_tendered = case when p_payment_method = 'Cash' then p_amount_tendered end,
    change_due      = v_change,
    points_earned   = v_points
  where id = v_txn_id;

  return jsonb_build_object(
    'id', v_txn_id, 'txn_code', v_code, 'created_at', v_created,
    'subtotal', v_subtotal, 'discount_pct', p_discount_pct, 'discount_amount', v_discount,
    'tax', v_tax, 'vat_rate', v_settings.vat_rate, 'total', v_total,
    'payment_method', p_payment_method, 'amount_tendered', p_amount_tendered, 'change_due', v_change,
    'points_earned', v_points,
    'customer_points', case when p_customer_id is not null then v_cust.points + v_points end,
    'cashier_name', v_name
  );
end;
$$;

-- ── Refund a whole sale (owner only) ────────────────────────────────────────
-- Puts the items back in stock and takes back the customer's points.
create function public.ms_refund(p_txn_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_txn   public.ms_transactions;
  v_item  record;
  v_old   integer;
  v_name  text;
  v_spent numeric;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can refund sales'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Please give a reason for the refund'; end if;

  select * into v_txn from public.ms_transactions where id = p_txn_id for update;
  if not found then raise exception 'Sale not found'; end if;
  if v_txn.status = 'Refunded' then raise exception 'This sale was already refunded'; end if;

  select full_name into v_name from public.ms_profiles where id = auth.uid();

  for v_item in
    select ti.product_id, ti.quantity, coalesce(ti.product_name, p.name) as name
    from public.ms_transaction_items ti
    left join public.ms_products p on p.id = ti.product_id
    where ti.transaction_id = p_txn_id and ti.product_id is not null
  loop
    select stock into v_old from public.ms_inventory where product_id = v_item.product_id for update;
    if found then
      update public.ms_inventory set stock = stock + v_item.quantity, updated_at = now()
      where product_id = v_item.product_id;
      insert into public.ms_stock_movements (product_id, product_name, old_stock, new_stock, change, reason, created_by, created_by_name)
      values (v_item.product_id, v_item.name, v_old, v_old + v_item.quantity, v_item.quantity,
              'Refund ' || coalesce(v_txn.txn_code, '#' || v_txn.id), auth.uid(), v_name);
    end if;
  end loop;

  if v_txn.customer_id is not null then
    select greatest(0, total_spent - v_txn.total) into v_spent from public.ms_customers where id = v_txn.customer_id;
    update public.ms_customers set
      total_spent = v_spent,
      points      = greatest(0, points - coalesce(v_txn.points_earned, floor(v_txn.total)::int)),
      tier        = public.ms_tier(v_spent)
    where id = v_txn.customer_id;
  end if;

  update public.ms_transactions set
    status = 'Refunded', refunded_at = now(), refunded_by = auth.uid(), refund_reason = trim(p_reason)
  where id = p_txn_id;
end;
$$;

-- ── Change stock (staff) ────────────────────────────────────────────────────
-- p_mode 'add' = receive/add units (negative to take away), 'set' = stock count.
create function public.ms_adjust_stock(p_product_id bigint, p_quantity integer, p_mode text, p_reason text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old  integer;
  v_new  integer;
  v_name text;
  v_prod text;
begin
  if not public.ms_is_staff() then raise exception 'Not allowed'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Please give a reason for the stock change'; end if;

  select i.stock, p.name into v_old, v_prod
  from public.ms_inventory i join public.ms_products p on p.id = i.product_id
  where i.product_id = p_product_id
  for update of i;
  if not found then raise exception 'Product not found'; end if;

  v_new := case when p_mode = 'set' then p_quantity else v_old + p_quantity end;
  if v_new < 0 then raise exception 'Stock cannot go below zero'; end if;
  if v_new = v_old then return v_new; end if;

  select full_name into v_name from public.ms_profiles where id = auth.uid();

  update public.ms_inventory set stock = v_new, updated_at = now() where product_id = p_product_id;
  insert into public.ms_stock_movements (product_id, product_name, old_stock, new_stock, change, reason, created_by, created_by_name)
  values (p_product_id, v_prod, v_old, v_new, v_new - v_old, trim(p_reason), auth.uid(), v_name);
  return v_new;
end;
$$;

-- ── Add a product with its opening stock (staff) ────────────────────────────
create function public.ms_create_product(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id    bigint;
  v_stock integer := greatest(0, coalesce((p->>'stock')::int, 0));
  v_name  text;
begin
