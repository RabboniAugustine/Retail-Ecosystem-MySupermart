-- ============================================================================
-- 006_delete_sales.sql
-- Lets the owner delete a sale completely (e.g. a test sale or one rung up by
-- mistake). The sale disappears from every report as if it never happened:
--   * items go back into stock (unless the sale was already refunded),
--   * the customer's spend, visits and points are taken back,
--   * the money is removed from the Cash / Bank / Mobile Money account.
-- A copy of every deleted sale is kept in ms_deleted_records (owner only),
-- with who deleted it, when and why.
-- Safe to run more than once. Run AFTER 005.
-- ============================================================================

create table if not exists public.ms_deleted_records (
  id               bigint generated by default as identity primary key,
  record_type      text not null,          -- 'sale'
  record_code      text,
  amount           numeric(14,2),
  reason           text not null,
  snapshot         jsonb not null,         -- the full record and its items as they were
  deleted_by       uuid references auth.users(id) on delete set null,
  deleted_by_name  text,
  deleted_at       timestamptz not null default now()
);
create index if not exists ms_deleted_records_at_idx on public.ms_deleted_records (deleted_at desc);

alter table public.ms_deleted_records enable row level security;
revoke all on public.ms_deleted_records from anon;
drop policy if exists deleted_records_owner_read on public.ms_deleted_records;
create policy deleted_records_owner_read on public.ms_deleted_records for select to authenticated using (public.ms_is_owner());

create or replace function public.ms_delete_sale(p_txn_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_txn      public.ms_transactions;
  v_items    jsonb;
  v_item     record;
  v_name     text;
  v_spent    numeric;
  v_customer text;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can delete sales'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Please give a reason for deleting this sale'; end if;

  select * into v_txn from public.ms_transactions where id = p_txn_id for update;
  if not found then raise exception 'Sale not found (it may already have been deleted)'; end if;

  select full_name into v_name from public.ms_profiles where id = auth.uid();
  select name into v_customer from public.ms_customers where id = v_txn.customer_id;
  select coalesce(jsonb_agg(to_jsonb(ti) order by ti.id), '[]'::jsonb) into v_items
  from public.ms_transaction_items ti where ti.transaction_id = p_txn_id;

  if v_txn.status <> 'Refunded' then
    -- Put the goods back on the shelf. No stock-log line is written, because
    -- the sale is treated as never having happened (the deleted-sales log keeps the record).
    for v_item in
      select product_id, sum(quantity) as qty from public.ms_transaction_items
      where transaction_id = p_txn_id and product_id is not null group by product_id
    loop
      update public.ms_inventory set stock = stock + v_item.qty, updated_at = now() where product_id = v_item.product_id;
    end loop;

    -- Take back the customer's spend, visit and points.
    if v_txn.customer_id is not null then
      select greatest(0, total_spent - v_txn.total) into v_spent from public.ms_customers where id = v_txn.customer_id;
      update public.ms_customers set
        total_spent = v_spent,
        visit_count = greatest(0, visit_count - 1),
        points      = greatest(0, points - coalesce(v_txn.points_earned, floor(v_txn.total)::int)),
        tier        = public.ms_tier(v_spent)
      where id = v_txn.customer_id;
    end if;
  else
    -- Already refunded: stock and points were returned by the refund. Remove the
    -- refund's stock-log lines so the stock report does not count the goods twice.
    delete from public.ms_stock_movements
    where kind = 'refund' and reason = 'Refund ' || coalesce(v_txn.txn_code, '#' || v_txn.id);
    if v_txn.customer_id is not null then
      update public.ms_customers set visit_count = greatest(0, visit_count - 1) where id = v_txn.customer_id;
    end if;
  end if;

  -- Remove the sale (and refund) from the money accounts.
  delete from public.ms_money_movements where ref_type = 'transaction' and ref_id = p_txn_id;

  insert into public.ms_deleted_records (record_type, record_code, amount, reason, snapshot, deleted_by, deleted_by_name)
  values ('sale', v_txn.txn_code, v_txn.total, trim(p_reason),
          to_jsonb(v_txn) || jsonb_build_object('items', v_items, 'customer_name', v_customer),
          auth.uid(), v_name);

  delete from public.ms_transaction_items where transaction_id = p_txn_id;
  delete from public.ms_transactions where id = p_txn_id;
end;
$$;

revoke execute on function public.ms_delete_sale(bigint, text) from public, anon;
grant execute on function public.ms_delete_sale(bigint, text) to authenticated;
