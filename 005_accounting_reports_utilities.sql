-- ── Money accounts ledger ──────────────────────────────────────────────────
-- Every cedi that comes in or goes out, per account. Positive = money in,
-- negative = money out. The Bank Statement report reads from here.
-- Sales paid by Cash -> Cash, Card -> Bank, Mobile Money -> Mobile Money.
create table if not exists public.ms_money_movements (
  id               bigint generated by default as identity primary key,
  account          text not null check (account in ('Cash', 'Bank', 'Mobile Money')),
  amount           numeric(14,2) not null,
  kind             text not null,  -- sale, refund, purchase, supplier_payment, expense, transfer, money_in, money_out
  description      text not null,
  ref_type         text,           -- transaction, purchase, expense
  ref_id           bigint,
  occurred_at      timestamptz not null default now(),
  created_by       uuid references auth.users(id) on delete set null,
  created_by_name  text,
  created_at       timestamptz not null default now()
);
create index if not exists ms_money_movements_account_idx on public.ms_money_movements (account, occurred_at);
create index if not exists ms_money_movements_ref_idx on public.ms_money_movements (ref_type, ref_id);

create or replace function public.ms_payment_account(p_method text)
returns text language sql immutable as $$
  select case p_method when 'Card' then 'Bank' when 'Mobile Money' then 'Mobile Money' else 'Cash' end;
$$;

-- ── Stock movement kinds (for the Stock Summary report) ────────────────────
alter table public.ms_stock_movements add column if not exists kind text not null default 'adjust';
update public.ms_stock_movements set kind = case
    when reason like 'Refund %' then 'refund'
    when reason like 'Removed:%' then 'removal'
    when reason = 'Opening stock' then 'opening'
    else 'adjust' end
where kind = 'adjust' and (reason like 'Refund %' or reason like 'Removed:%' or reason = 'Opening stock');

-- Fill in the kind automatically when older functions (checkout refund,
-- product removal, opening stock) write a movement without one.
create or replace function public.ms_stock_movement_kind()
returns trigger language plpgsql as $$
begin
  if new.kind = 'adjust' then
    new.kind := case
      when new.reason like 'Refund %' then 'refund'
      when new.reason like 'Removed:%' then 'removal'
      when new.reason = 'Opening stock' then 'opening'
      else 'adjust' end;
  end if;
  return new;
end;
$$;
drop trigger if exists ms_stock_movement_kind on public.ms_stock_movements;
create trigger ms_stock_movement_kind before insert on public.ms_stock_movements
  for each row execute function public.ms_stock_movement_kind();

-- ── Sales and refunds feed the money ledger automatically ──────────────────
create or replace function public.ms_txn_to_ledger()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- Checkout finishes by replacing the temporary code with the real one.
  if coalesce(old.txn_code, '') like 'TMP-%' and new.txn_code not like 'TMP-%' and new.total > 0 then
    insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by, created_by_name)
    values (public.ms_payment_account(new.payment_method), new.total, 'sale', 'Sale ' || new.txn_code,
            'transaction', new.id, new.created_at, new.cashier_id, new.cashier_name);
  end if;
  if old.status <> 'Refunded' and new.status = 'Refunded' then
    insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by, created_by_name)
    values (public.ms_payment_account(new.payment_method), -new.total, 'refund', 'Refund ' || new.txn_code,
            'transaction', new.id, coalesce(new.refunded_at, now()), new.refunded_by,
            (select full_name from public.ms_profiles where id = new.refunded_by));
  end if;
  return new;
end;
$$;
drop trigger if exists ms_txn_to_ledger on public.ms_transactions;
create trigger ms_txn_to_ledger after update on public.ms_transactions
  for each row execute function public.ms_txn_to_ledger();

-- Past sales and refunds go into the ledger once.
insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by, created_by_name)
select public.ms_payment_account(t.payment_method), t.total, 'sale', 'Sale ' || t.txn_code, 'transaction', t.id, t.created_at, t.cashier_id, t.cashier_name
from public.ms_transactions t
where t.txn_code not like 'TMP-%' and t.total > 0
  and not exists (select 1 from public.ms_money_movements m where m.ref_type = 'transaction' and m.ref_id = t.id and m.kind = 'sale');
insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by)
select public.ms_payment_account(t.payment_method), -t.total, 'refund', 'Refund ' || t.txn_code, 'transaction', t.id, coalesce(t.refunded_at, t.created_at), t.refunded_by
from public.ms_transactions t
where t.status = 'Refunded'
  and not exists (select 1 from public.ms_money_movements m where m.ref_type = 'transaction' and m.ref_id = t.id and m.kind = 'refund');

-- ── Expenses: staff can record them; each one leaves an account ────────────
alter table public.ms_expenses add column if not exists paid_from text not null default 'Cash';
alter table public.ms_expenses add column if not exists created_by_name text;
alter table public.ms_expenses add column if not exists created_at timestamptz not null default now();
alter table public.ms_expenses alter column created_by set default auth.uid();
do $$ begin
  alter table public.ms_expenses add constraint ms_expenses_paid_from_check check (paid_from in ('Cash', 'Bank', 'Mobile Money'));
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.ms_expenses add constraint ms_expenses_amount_check check (amount > 0) not valid;
exception when duplicate_object then null; end $$;

create or replace function public.ms_expense_fill()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := coalesce(new.created_by, auth.uid());
    new.created_by_name := (select full_name from public.ms_profiles where id = new.created_by);
  end if;
  return new;
end;
$$;
drop trigger if exists ms_expense_fill on public.ms_expenses;
create trigger ms_expense_fill before insert on public.ms_expenses
  for each row execute function public.ms_expense_fill();

create or replace function public.ms_expense_to_ledger()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    delete from public.ms_money_movements where ref_type = 'expense' and ref_id = old.id;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by, created_by_name)
    values (new.paid_from, -new.amount, 'expense', 'Expense: ' || new.description || ' (' || new.category || ')',
            'expense', new.id, new.date::timestamptz + interval '12 hours', new.created_by, new.created_by_name);
    return new;
  end if;
  return old;
end;
$$;
drop trigger if exists ms_expense_to_ledger on public.ms_expenses;
create trigger ms_expense_to_ledger after insert or update or delete on public.ms_expenses
  for each row execute function public.ms_expense_to_ledger();

-- Past expenses go into the ledger once (assumed paid in cash).
insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by)
select e.paid_from, -e.amount, 'expense', 'Expense: ' || e.description || ' (' || e.category || ')', 'expense', e.id,
       e.date::timestamptz + interval '12 hours', e.created_by
from public.ms_expenses e
where not exists (select 1 from public.ms_money_movements m where m.ref_type = 'expense' and m.ref_id = e.id);

-- ── Purchases (stock bought from suppliers) ────────────────────────────────
create table if not exists public.ms_purchases (
  id               bigint generated by default as identity primary key,
  purchase_code    text unique,
  supplier_id      bigint references public.ms_suppliers(id) on delete set null,
  supplier_name    text,
  invoice_no       text,
  purchase_date    date not null default current_date,
  total            numeric(14,2) not null default 0,
  amount_paid      numeric(14,2) not null default 0,
  status           text not null default 'Unpaid' check (status in ('Paid', 'Part paid', 'Unpaid', 'Void')),
  note             text,
  created_by       uuid references auth.users(id) on delete set null,
  created_by_name  text,
  created_at       timestamptz not null default now(),
  voided_at        timestamptz,
  voided_by_name   text,
  void_reason      text
);
create index if not exists ms_purchases_date_idx on public.ms_purchases (purchase_date desc);

create table if not exists public.ms_purchase_items (
  id            bigint generated by default as identity primary key,
  purchase_id   bigint not null references public.ms_purchases(id) on delete cascade,
  product_id    bigint references public.ms_products(id) on delete set null,
  product_name  text not null,
  quantity      integer not null check (quantity > 0),
  unit_cost     numeric(12,2) not null check (unit_cost >= 0),
  line_total    numeric(14,2) not null
);
create index if not exists ms_purchase_items_purchase_idx on public.ms_purchase_items (purchase_id);

create or replace function public.ms_purchase_status(p_total numeric, p_paid numeric)
returns text language sql immutable as $$
  select case when p_paid >= p_total then 'Paid' when p_paid > 0 then 'Part paid' else 'Unpaid' end;
$$;

-- Record a purchase: stock goes up, cost price is updated to the new cost,
-- the amount paid leaves the chosen account, and anything unpaid is owed to the supplier.
-- p: {supplier_id, invoice_no, purchase_date, note, amount_paid, paid_from,
--     items: [{product_id, quantity, unit_cost, new_price}]}
create or replace function public.ms_create_purchase(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id       bigint;
  v_code     text;
  v_name     text;
  v_supplier public.ms_suppliers;
  v_item     record;
  v_prod     record;
  v_total    numeric := 0;
  v_paid     numeric := greatest(0, coalesce((p->>'amount_paid')::numeric, 0));
  v_from     text := coalesce(nullif(p->>'paid_from', ''), 'Cash');
  v_date     date := coalesce(nullif(p->>'purchase_date', '')::date, current_date);
begin
  if not public.ms_is_staff() then raise exception 'Not allowed'; end if;
  if jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 then
    raise exception 'Add at least one item to the purchase';
  end if;
  if v_from not in ('Cash', 'Bank', 'Mobile Money') then raise exception 'Unknown account %', v_from; end if;
  if v_date > current_date + 1 then raise exception 'The purchase date cannot be in the future'; end if;

  if nullif(p->>'supplier_id', '') is not null then
    select * into v_supplier from public.ms_suppliers where id = (p->>'supplier_id')::bigint;
    if not found then raise exception 'Supplier not found'; end if;
  end if;

  select full_name into v_name from public.ms_profiles where id = auth.uid();

  insert into public.ms_purchases (purchase_code, supplier_id, supplier_name, invoice_no, purchase_date, note, created_by, created_by_name)
  values ('TMP-' || gen_random_uuid(), v_supplier.id, v_supplier.name, nullif(trim(p->>'invoice_no'), ''), v_date,
          nullif(trim(p->>'note'), ''), auth.uid(), v_name)
  returning id into v_id;
  v_code := 'PUR-' || to_char(v_date, 'YYMMDD') || '-' || lpad(v_id::text, 5, '0');

  for v_item in
    select (e->>'product_id')::bigint as product_id,
           (e->>'quantity')::int as qty,
           (e->>'unit_cost')::numeric as unit_cost,
           nullif(e->>'new_price', '')::numeric as new_price
    from jsonb_array_elements(p->'items') e
  loop
    if v_item.qty is null or v_item.qty <= 0 then raise exception 'Quantities must be at least 1'; end if;
    if v_item.unit_cost is null or v_item.unit_cost < 0 then raise exception 'Unit cost cannot be negative'; end if;
    if v_item.new_price is not null and v_item.new_price < 0 then raise exception 'Selling price cannot be negative'; end if;

    select pr.id, pr.name, i.stock into v_prod
    from public.ms_products pr join public.ms_inventory i on i.product_id = pr.id
    where pr.id = v_item.product_id and pr.active
    for update of i;
    if not found then raise exception 'A product in this purchase was not found'; end if;

    insert into public.ms_purchase_items (purchase_id, product_id, product_name, quantity, unit_cost, line_total)
    values (v_id, v_prod.id, v_prod.name, v_item.qty, v_item.unit_cost, round(v_item.qty * v_item.unit_cost, 2));

    update public.ms_inventory set stock = stock + v_item.qty, updated_at = now(),
      supplier = coalesce(v_supplier.name, supplier)
    where product_id = v_prod.id;
    update public.ms_products set cost = v_item.unit_cost, price = coalesce(v_item.new_price, price)
    where id = v_prod.id;

    insert into public.ms_stock_movements (product_id, product_name, old_stock, new_stock, change, reason, kind, created_by, created_by_name)
    values (v_prod.id, v_prod.name, v_prod.stock, v_prod.stock + v_item.qty, v_item.qty, 'Purchase ' || v_code, 'purchase', auth.uid(), v_name);

    v_total := v_total + round(v_item.qty * v_item.unit_cost, 2);
  end loop;

  if v_paid > v_total then v_paid := v_total; end if;
  if v_paid < v_total and v_supplier.id is null then
    raise exception 'Choose the supplier when the purchase is not fully paid, so the amount owed is recorded';
  end if;

  update public.ms_purchases set purchase_code = v_code, total = v_total, amount_paid = v_paid,
    status = public.ms_purchase_status(v_total, v_paid)
  where id = v_id;

  if v_supplier.id is not null and v_total - v_paid > 0 then
    update public.ms_suppliers set payable = payable + (v_total - v_paid) where id = v_supplier.id;
  end if;

  if v_paid > 0 then
    insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by, created_by_name)
    values (v_from, -v_paid, 'purchase', 'Purchase ' || v_code || coalesce(' from ' || v_supplier.name, ''),
            'purchase', v_id, v_date::timestamptz + interval '12 hours', auth.uid(), v_name);
  end if;

  return jsonb_build_object('id', v_id, 'purchase_code', v_code, 'total', v_total, 'amount_paid', v_paid);
end;
$$;

-- Pay (part of) what is still owed on a purchase.
create or replace function public.ms_pay_purchase(p_purchase_id bigint, p_amount numeric, p_account text, p_date date default current_date)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pur  public.ms_purchases;
  v_name text;
  v_due  numeric;
begin
  if not public.ms_is_staff() then raise exception 'Not allowed'; end if;
  if p_account not in ('Cash', 'Bank', 'Mobile Money') then raise exception 'Unknown account %', p_account; end if;
  select * into v_pur from public.ms_purchases where id = p_purchase_id for update;
  if not found then raise exception 'Purchase not found'; end if;
  if v_pur.status = 'Void' then raise exception 'This purchase was voided'; end if;
  v_due := v_pur.total - v_pur.amount_paid;
  if v_due <= 0 then raise exception 'This purchase is already fully paid'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter the amount paid'; end if;
  if p_amount > v_due then raise exception 'Only ₵% is still owed on this purchase', v_due; end if;

  select full_name into v_name from public.ms_profiles where id = auth.uid();
  update public.ms_purchases set amount_paid = amount_paid + p_amount,
    status = public.ms_purchase_status(total, amount_paid + p_amount)
  where id = p_purchase_id;
  if v_pur.supplier_id is not null then
    update public.ms_suppliers set payable = greatest(0, payable - p_amount) where id = v_pur.supplier_id;
  end if;
  insert into public.ms_money_movements (account, amount, kind, description, ref_type, ref_id, occurred_at, created_by, created_by_name)
  values (p_account, -p_amount, 'supplier_payment', 'Payment for ' || v_pur.purchase_code || coalesce(' to ' || v_pur.supplier_name, ''),
          'purchase', v_pur.id, coalesce(p_date, current_date)::timestamptz + interval '12 hours', auth.uid(), v_name);
end;
$$;

-- Void a purchase entered by mistake (owner only): takes the stock back out,
-- cancels what was owed and removes its payments from the accounts.
create or replace function public.ms_void_purchase(p_purchase_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pur  public.ms_purchases;
  v_name text;
  v_item record;
  v_old  integer;
  v_new  integer;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can void purchases'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Please give a reason'; end if;
  select * into v_pur from public.ms_purchases where id = p_purchase_id for update;
  if not found then raise exception 'Purchase not found'; end if;
  if v_pur.status = 'Void' then raise exception 'This purchase is already void'; end if;
  select full_name into v_name from public.ms_profiles where id = auth.uid();

  for v_item in select * from public.ms_purchase_items where purchase_id = p_purchase_id and product_id is not null loop
    select stock into v_old from public.ms_inventory where product_id = v_item.product_id for update;
    if found then
      v_new := greatest(0, v_old - v_item.quantity);
      update public.ms_inventory set stock = v_new, updated_at = now() where product_id = v_item.product_id;
      insert into public.ms_stock_movements (product_id, product_name, old_stock, new_stock, change, reason, kind, created_by, created_by_name)
      values (v_item.product_id, v_item.product_name, v_old, v_new, v_new - v_old, 'Void ' || v_pur.purchase_code, 'purchase', auth.uid(), v_name);
    end if;
  end loop;

  if v_pur.supplier_id is not null and v_pur.total - v_pur.amount_paid > 0 then
    update public.ms_suppliers set payable = greatest(0, payable - (v_pur.total - v_pur.amount_paid)) where id = v_pur.supplier_id;
  end if;
  delete from public.ms_money_movements where ref_type = 'purchase' and ref_id = p_purchase_id;

  update public.ms_purchases set status = 'Void', voided_at = now(), voided_by_name = v_name, void_reason = trim(p_reason)
  where id = p_purchase_id;
end;
$$;

-- ── Owner money entries: transfers, money in, money out ────────────────────
-- e.g. "Deposit cash in the bank" = transfer Cash -> Bank.
create or replace function public.ms_money_entry(p_kind text, p_amount numeric, p_from text, p_to text, p_description text, p_date date default current_date)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  v_at   timestamptz := coalesce(p_date, current_date)::timestamptz + interval '12 hours';
  v_desc text := nullif(trim(p_description), '');
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can record money movements'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter an amount above zero'; end if;
  select full_name into v_name from public.ms_profiles where id = auth.uid();
  if p_kind = 'transfer' then
    if p_from is null or p_to is null or p_from = p_to then raise exception 'Choose two different accounts'; end if;
    insert into public.ms_money_movements (account, amount, kind, description, occurred_at, created_by, created_by_name) values
      (p_from, -p_amount, 'transfer', coalesce(v_desc, 'Transfer to ' || p_to), v_at, auth.uid(), v_name),
      (p_to, p_amount, 'transfer', coalesce(v_desc, 'Transfer from ' || p_from), v_at, auth.uid(), v_name);
  elsif p_kind = 'money_in' then
    if p_to is null then raise exception 'Choose the account'; end if;
    insert into public.ms_money_movements (account, amount, kind, description, occurred_at, created_by, created_by_name)
    values (p_to, p_amount, 'money_in', coalesce(v_desc, 'Money in'), v_at, auth.uid(), v_name);
  elsif p_kind = 'money_out' then
    if p_from is null then raise exception 'Choose the account'; end if;
    insert into public.ms_money_movements (account, amount, kind, description, occurred_at, created_by, created_by_name)
    values (p_from, -p_amount, 'money_out', coalesce(v_desc, 'Money out'), v_at, auth.uid(), v_name);
  else
    raise exception 'Unknown entry type %', p_kind;
  end if;
end;
$$;

create or replace function public.ms_account_balances()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can see account balances'; end if;
  return (
    select jsonb_object_agg(a.account, coalesce(b.bal, 0))
    from (values ('Cash'), ('Bank'), ('Mobile Money')) a(account)
    left join (select account, sum(amount) bal from public.ms_money_movements group by account) b using (account)
  );
end;
$$;

-- ── Utilities: import new items and update items in bulk (owner only) ──────
-- Each row is handled on its own: a bad row is reported and skipped, the rest are saved.
create or replace function public.ms_import_items(p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row     jsonb;
  v_idx     int := 0;
  v_created int := 0;
  v_errors  jsonb := '[]'::jsonb;
  v_id      bigint;
  v_stock   int;
  v_name    text;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can import items'; end if;
  select full_name into v_name from public.ms_profiles where id = auth.uid();
  for v_row in select * from jsonb_array_elements(p_rows) loop
    v_idx := v_idx + 1;
    begin
      if coalesce(trim(v_row->>'name'), '') = '' then raise exception 'Name is missing'; end if;
      if nullif(trim(v_row->>'sku'), '') is not null and exists (select 1 from public.ms_products where lower(sku) = lower(trim(v_row->>'sku'))) then
        raise exception 'SKU % already exists', trim(v_row->>'sku');
      end if;
      if nullif(trim(v_row->>'barcode'), '') is not null and exists (select 1 from public.ms_products where barcode = trim(v_row->>'barcode') and active) then
        raise exception 'Barcode % already exists', trim(v_row->>'barcode');
      end if;
      v_stock := greatest(0, coalesce(nullif(v_row->>'stock', '')::numeric, 0))::int;
      insert into public.ms_products (name, sku, barcode, category, price, cost)
      values (trim(v_row->>'name'), nullif(trim(v_row->>'sku'), ''), nullif(trim(v_row->>'barcode'), ''),
              coalesce(nullif(trim(v_row->>'category'), ''), 'Other'),
              greatest(0, coalesce(nullif(v_row->>'price', '')::numeric, 0)),
              greatest(0, coalesce(nullif(v_row->>'cost', '')::numeric, 0)))
      returning id into v_id;
      insert into public.ms_inventory (product_id, stock, reorder_level, expiry_date, supplier)
      values (v_id, v_stock, greatest(0, coalesce(nullif(v_row->>'reorder_level', '')::numeric, 0))::int,
              nullif(v_row->>'expiry_date', '')::date, nullif(trim(v_row->>'supplier'), ''));
      if v_stock > 0 then
        insert into public.ms_stock_movements (product_id, product_name, old_stock, new_stock, change, reason, kind, created_by, created_by_name)
        values (v_id, trim(v_row->>'name'), 0, v_stock, v_stock, 'Imported', 'opening', auth.uid(), v_name);
      end if;
      v_created := v_created + 1;
    exception when others then
      v_errors := v_errors || jsonb_build_object('row', coalesce((v_row->>'_row')::int, v_idx), 'name', v_row->>'name', 'error', sqlerrm);
    end;
  end loop;
  return jsonb_build_object('created', v_created, 'errors', v_errors);
end;
$$;

-- p_rows: [{product_id, name?, sku?, barcode?, category?, price?, cost?, reorder_level?, supplier?, expiry_date?, stock?}]
-- Only the fields present are changed. A new stock number is logged as a stock count.
create or replace function public.ms_bulk_update_items(p_rows jsonb, p_reason text default 'Bulk update')
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row     jsonb;
  v_idx     int := 0;
  v_updated int := 0;
  v_errors  jsonb := '[]'::jsonb;
  v_pid     bigint;
  v_old     int;
  v_new     int;
  v_pname   text;
  v_name    text;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can update items in bulk'; end if;
  select full_name into v_name from public.ms_profiles where id = auth.uid();
  for v_row in select * from jsonb_array_elements(p_rows) loop
    v_idx := v_idx + 1;
    v_pname := null;
    begin
      v_pid := (v_row->>'product_id')::bigint;
      if not exists (select 1 from public.ms_products where id = v_pid and active) then raise exception 'Product not found'; end if;
      if v_row ? 'price' and (v_row->>'price')::numeric < 0 then raise exception 'Price cannot be negative'; end if;
      if v_row ? 'cost' and (v_row->>'cost')::numeric < 0 then raise exception 'Cost cannot be negative'; end if;

      update public.ms_products set
        name     = case when v_row ? 'name' and trim(v_row->>'name') <> '' then trim(v_row->>'name') else name end,
        sku      = case when v_row ? 'sku' then nullif(trim(v_row->>'sku'), '') else sku end,
        barcode  = case when v_row ? 'barcode' then nullif(trim(v_row->>'barcode'), '') else barcode end,
        category = case when v_row ? 'category' and trim(v_row->>'category') <> '' then trim(v_row->>'category') else category end,
        price    = case when v_row ? 'price' then (v_row->>'price')::numeric else price end,
        cost     = case when v_row ? 'cost' then (v_row->>'cost')::numeric else cost end
      where id = v_pid
      returning name into v_pname;

      update public.ms_inventory set
        reorder_level = case when v_row ? 'reorder_level' then greatest(0, (v_row->>'reorder_level')::numeric)::int else reorder_level end,
        supplier      = case when v_row ? 'supplier' then nullif(trim(v_row->>'supplier'), '') else supplier end,
        expiry_date   = case when v_row ? 'expiry_date' then nullif(v_row->>'expiry_date', '')::date else expiry_date end,
        updated_at    = now()
      where product_id = v_pid;

      if v_row ? 'stock' and nullif(v_row->>'stock', '') is not null then
        v_new := (v_row->>'stock')::numeric::int;
        if v_new < 0 then raise exception 'Stock cannot be negative'; end if;
        select stock into v_old from public.ms_inventory where product_id = v_pid for update;
        if v_old is distinct from v_new then
          update public.ms_inventory set stock = v_new where product_id = v_pid;
          insert into public.ms_stock_movements (product_id, product_name, old_stock, new_stock, change, reason, kind, created_by, created_by_name)
          values (v_pid, v_pname, v_old, v_new, v_new - v_old, coalesce(nullif(trim(p_reason), ''), 'Bulk update'), 'adjust', auth.uid(), v_name);
        end if;
      end if;
      v_updated := v_updated + 1;
    exception when others then
      v_errors := v_errors || jsonb_build_object('row', coalesce((v_row->>'_row')::int, v_idx), 'name', coalesce(v_pname, v_row->>'name'), 'error',
        case when sqlstate = '23505' then 'That SKU or barcode is already used by another item' else sqlerrm end);
    end;
  end loop;
  return jsonb_build_object('updated', v_updated, 'errors', v_errors);
end;
$$;

-- ── Reports (owner only) ───────────────────────────────────────────────────
-- Dates are calendar days in the shop's time zone (p_tz), inclusive.

create or replace function public.ms_report_sales(p_from date, p_to date, p_tz text default 'Africa/Accra')
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can view reports'; end if;
  with t as (
    select *, (created_at at time zone p_tz)::date as day
    from public.ms_transactions
    where (created_at at time zone p_tz)::date between p_from and p_to and txn_code not like 'TMP-%'
  ), done as (select * from t where status <> 'Refunded'),
  items as (
    select ti.*, coalesce(ti.product_name, pr.name, 'Removed product') as pname, coalesce(pr.category, 'Other') as category
    from public.ms_transaction_items ti
    join done on done.id = ti.transaction_id
    left join public.ms_products pr on pr.id = ti.product_id
  )
  select jsonb_build_object(
    'totals', (select jsonb_build_object(
        'count', count(*), 'gross', coalesce(sum(subtotal), 0),
        'discount', coalesce(sum(coalesce(discount_amount, round(subtotal * discount_pct / 100, 2))), 0),
        'vat', coalesce(sum(tax), 0), 'total', coalesce(sum(total), 0)) from done),
    'refunds', (select jsonb_build_object('count', count(*), 'total', coalesce(sum(total), 0)) from t where status = 'Refunded'),
    'items_sold', (select coalesce(sum(quantity), 0) from items),
    'by_day', coalesce((select jsonb_agg(x order by x.day) from (
        select day, count(*) as count, sum(total) as total from done group by day) x), '[]'::jsonb),
    'by_payment', coalesce((select jsonb_agg(x order by x.total desc) from (
        select payment_method as name, count(*) as count, sum(total) as total from done group by 1) x), '[]'::jsonb),
    'by_staff', coalesce((select jsonb_agg(x order by x.total desc) from (
        select coalesce(cashier_name, 'Unassigned') as name, count(*) as count, sum(total) as total from done group by 1) x), '[]'::jsonb),
    'by_product', coalesce((select jsonb_agg(x order by x.revenue desc) from (
        select pname as name, category, sum(quantity) as qty, sum(line_total) as revenue from items group by 1, 2) x), '[]'::jsonb),
    'by_category', coalesce((select jsonb_agg(x order by x.revenue desc) from (
        select category as name, sum(quantity) as qty, sum(line_total) as revenue from items group by 1) x), '[]'::jsonb)
  ) into v;
  return v;
end;
$$;

create or replace function public.ms_report_pnl(p_from date, p_to date, p_tz text default 'Africa/Accra')
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_sales numeric; v_discount numeric; v_vat numeric; v_cogs numeric; v_cogs_est boolean;
  v_exp jsonb; v_exp_total numeric; v_loss numeric; v_purch numeric;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can view reports'; end if;

  select coalesce(sum(subtotal), 0), coalesce(sum(coalesce(discount_amount, round(subtotal * discount_pct / 100, 2))), 0), coalesce(sum(tax), 0)
  into v_sales, v_discount, v_vat
  from public.ms_transactions
  where status <> 'Refunded' and txn_code not like 'TMP-%' and (created_at at time zone p_tz)::date between p_from and p_to;

  -- Cost of goods sold uses the cost at the time of sale; older sales without it use today's cost.
  select coalesce(sum(ti.quantity * coalesce(ti.unit_cost, pr.cost, 0)), 0), coalesce(bool_or(ti.unit_cost is null), false)
  into v_cogs, v_cogs_est
  from public.ms_transaction_items ti
  join public.ms_transactions t on t.id = ti.transaction_id
  left join public.ms_products pr on pr.id = ti.product_id
  where t.status <> 'Refunded' and t.txn_code not like 'TMP-%' and (t.created_at at time zone p_tz)::date between p_from and p_to;

  select coalesce(jsonb_agg(x order by x.total desc), '[]'::jsonb), coalesce(sum(x.total), 0) into v_exp, v_exp_total
  from (select category as name, sum(amount) as total from public.ms_expenses where date between p_from and p_to group by 1) x;

  select coalesce(sum(loss_value), 0) into v_loss from public.ms_product_removals
  where (removed_at at time zone p_tz)::date between p_from and p_to;

  select coalesce(sum(total), 0) into v_purch from public.ms_purchases
  where status <> 'Void' and purchase_date between p_from and p_to;

  return jsonb_build_object(
    'sales', v_sales, 'discount', v_discount, 'net_sales', v_sales - v_discount, 'vat', v_vat,
    'cogs', v_cogs, 'cogs_estimated', v_cogs_est, 'gross_profit', v_sales - v_discount - v_cogs,
    'expenses', v_exp, 'expenses_total', v_exp_total, 'stock_loss', v_loss,
    'net_profit', v_sales - v_discount - v_cogs - v_exp_total - v_loss,
    'purchases', v_purch
  );
end;
$$;

-- Opening stock, bought, sold, other changes and closing stock per product.
create or replace function public.ms_report_stock(p_from date, p_to date, p_tz text default 'Africa/Accra')
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can view reports'; end if;
  with mv as (
    select product_id,
      sum(change) filter (where (created_at at time zone p_tz)::date > p_to) as after_mv,
      sum(change) filter (where kind = 'purchase' and (created_at at time zone p_tz)::date between p_from and p_to) as bought,
      sum(change) filter (where kind <> 'purchase' and (created_at at time zone p_tz)::date between p_from and p_to) as other
    from public.ms_stock_movements where product_id is not null group by product_id
  ), sold as (
    select ti.product_id,
      sum(ti.quantity) filter (where (t.created_at at time zone p_tz)::date > p_to) as after_sold,
      sum(ti.quantity) filter (where (t.created_at at time zone p_tz)::date between p_from and p_to) as sold
    from public.ms_transaction_items ti join public.ms_transactions t on t.id = ti.transaction_id
    where ti.product_id is not null and t.txn_code not like 'TMP-%'
    group by ti.product_id
  ), rows as (
    select pr.id, pr.name, pr.sku, pr.category, pr.cost, pr.price, i.reorder_level,
      i.stock - coalesce(mv.after_mv, 0) + coalesce(sold.after_sold, 0) as closing,
      coalesce(mv.bought, 0) as bought, coalesce(sold.sold, 0) as sold, coalesce(mv.other, 0) as other
    from public.ms_products pr
    join public.ms_inventory i on i.product_id = pr.id
    left join mv on mv.product_id = pr.id
    left join sold on sold.product_id = pr.id
    where pr.active or coalesce(mv.bought, 0) <> 0 or coalesce(sold.sold, 0) <> 0 or coalesce(mv.other, 0) <> 0
  )
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', id, 'name', name, 'sku', sku, 'category', category, 'cost', cost, 'price', price, 'reorder_level', reorder_level,
      'opening', closing - bought - other + sold, 'bought', bought, 'sold', sold, 'other', other, 'closing', closing,
      'value', round(greatest(closing, 0) * cost, 2)) order by category, name), '[]'::jsonb)
  into v from rows;
  return v;
end;
$$;

-- Account statement with running balance. Sales are grouped into one line per day.
create or replace function public.ms_report_statement(p_account text, p_from date, p_to date, p_tz text default 'Africa/Accra')
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_open numeric; v_lines jsonb;
begin
  if not public.ms_is_owner() then raise exception 'Only the owner can view reports'; end if;
  select coalesce(sum(amount), 0) into v_open from public.ms_money_movements
  where account = p_account and (occurred_at at time zone p_tz)::date < p_from;

  with m as (
    select * from public.ms_money_movements
    where account = p_account and (occurred_at at time zone p_tz)::date between p_from and p_to
  ), lines as (
    select (occurred_at at time zone p_tz)::date as day, min(occurred_at) as at,
      'Sales (' || count(*) || ')' as description, sum(amount) as amount, 'sale' as kind
    from m where kind = 'sale' group by 1
    union all
    select (occurred_at at time zone p_tz)::date, occurred_at, description, amount, kind
    from m where kind <> 'sale'
  )
  select coalesce(jsonb_agg(jsonb_build_object(
      'date', day, 'description', description, 'kind', kind,
      'money_in', case when amount > 0 then amount else 0 end,
      'money_out', case when amount < 0 then -amount else 0 end) order by day, (kind <> 'sale'), at), '[]'::jsonb)
  into v_lines from lines;

  return jsonb_build_object('opening', v_open, 'lines', v_lines,
    'closing', v_open + coalesce((select sum(amount) from public.ms_money_movements
      where account = p_account and (occurred_at at time zone p_tz)::date between p_from and p_to), 0));
end;
$$;

